from data.dental_products import DENTAL_INSURANCE_PRODUCTS  # noqa: E402

ALL_PRODUCTS = LIFE_INSURANCE_PRODUCTS + HEALTH_INSURANCE_PRODUCTS + DENTAL_INSURANCE_PRODUCTS


def get_all_products():
    return ALL_PRODUCTS


def get_product_by_id(product_id: str):
    for p in ALL_PRODUCTS:
        if p["id"] == product_id:
            return p
    return None


def get_products_by_type(insurance_type: str):
    """insurance_type: '생명보험', '실손의료보험', or '덴탈보험'"""
    return [p for p in ALL_PRODUCTS if p["type"] == insurance_type]


def get_available_types() -> list[str]:
    """현재 카탈로그의 보험 유형 목록"""
    return sorted({p["type"] for p in ALL_PRODUCTS})
